package pipeline

import (
	"bytes"
	"compress/gzip"
	"hash/crc32"
	"testing"
)

func makeGzip(t *testing.T, data []byte) []byte {
	t.Helper()
	var compressed bytes.Buffer
	writer := gzip.NewWriter(&compressed)
	if _, err := writer.Write(data); err != nil {
		t.Fatalf("gzip write: %v", err)
	}
	if err := writer.Close(); err != nil {
		t.Fatalf("gzip close: %v", err)
	}
	return compressed.Bytes()
}

func TestGzipHeaderWriterValidatesInputTrailer(t *testing.T) {
	input := bytes.Repeat([]byte("fpga-gzip-payload-"), 37)
	compressed := makeGzip(t, input)

	var output bytes.Buffer
	writer := &gzipHeaderWriter{dst: &output}
	for _, part := range [][]byte{
		compressed[:3],
		compressed[3:10],
		compressed[10 : len(compressed)-2],
		compressed[len(compressed)-2:],
	} {
		if n, err := writer.Write(part); err != nil || n != len(part) {
			t.Fatalf("write part: n=%d err=%v", n, err)
		}
	}

	if err := writer.Validate(crc32.ChecksumIEEE(input), uint64(len(input))); err != nil {
		t.Fatalf("valid gzip rejected: %v", err)
	}
	if !bytes.Equal(output.Bytes(), compressed) {
		t.Fatal("validated writer changed the gzip stream")
	}
}

func TestGzipHeaderWriterRejectsValidGzipForWrongInput(t *testing.T) {
	actual := []byte("payload generated by the FPGA")
	expected := []byte("different input")
	compressed := makeGzip(t, actual)

	var output bytes.Buffer
	writer := &gzipHeaderWriter{dst: &output}
	if n, err := writer.Write(compressed); err != nil || n != len(compressed) {
		t.Fatalf("write gzip: n=%d err=%v", n, err)
	}
	if err := writer.Validate(crc32.ChecksumIEEE(expected), uint64(len(expected))); err == nil {
		t.Fatal("valid gzip with wrong payload was accepted")
	}
}

func TestGzipHeaderWriterRejectsShortTrailer(t *testing.T) {
	input := []byte("short trailer")
	compressed := makeGzip(t, input)
	compressed = compressed[:len(compressed)-1]

	var output bytes.Buffer
	writer := &gzipHeaderWriter{dst: &output}
	if _, err := writer.Write(compressed); err != nil {
		t.Fatalf("write truncated gzip: %v", err)
	}
	if err := writer.Validate(crc32.ChecksumIEEE(input), uint64(len(input))); err == nil {
		t.Fatal("truncated gzip was accepted")
	}
}
